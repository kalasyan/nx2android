# The companion page's touch listener as a dex file (kalasyan fork), written by hand: the APK has no Java code and no Java tools are needed.
# One class, org.nx2a.CompanionTouch implements android.view.View.OnTouchListener, whose only method onTouch is native (companion_android.c registers
# it and makes the object with AllocObject, so the class needs no constructor). companion_android.c loads it with InMemoryDexClassLoader (API 26).
#   python companion_dex.py > ../companion_touch_dex.h
import hashlib, struct, sys, zlib

STRINGS = sorted(['Landroid/view/MotionEvent;', 'Landroid/view/View$OnTouchListener;', 'Landroid/view/View;', 'Ljava/lang/Object;',
                  'Lorg/nx2a/CompanionTouch;', 'Z', 'ZLL', 'onTouch'])
TYPES = [s for s in STRINGS if s[0] == 'L' or s == 'Z']   # every type's descriptor, in string order (type_ids are sorted by their string)
S, T = STRINGS.index, lambda d: TYPES.index(d)
NO_INDEX = 0xffffffff


def uleb(n):
    out = bytearray()
    while True:
        b = n & 0x7f; n >>= 7
        out.append(b | (0x80 if n else 0))
        if not n: return bytes(out)


def align(b, n=4): return b + b'\0' * (-len(b) % n)


def build():
    n_str, n_type, n_proto, n_meth, n_cls = len(STRINGS), len(TYPES), 1, 1, 1
    off = 0x70
    o_str = off; off += 4 * n_str
    o_type = off; off += 4 * n_type
    o_proto = off; off += 12 * n_proto
    o_meth = off; off += 8 * n_meth
    o_cls = off; off += 32 * n_cls
    o_data = off
    data = bytearray()
    def put(b, a=1):
        nonlocal data
        data += b'\0' * (-(o_data + len(data)) % a); at = o_data + len(data); data += b; return at
    o_params = put(struct.pack('<IHH', 2, T('Landroid/view/View;'), T('Landroid/view/MotionEvent;')), 4)   # type_list (View, MotionEvent)
    o_ifaces = put(struct.pack('<IH', 1, T('Landroid/view/View$OnTouchListener;')), 4)
    o_sdata = []
    for s in STRINGS: o_sdata.append(put(uleb(len(s)) + s.encode('ascii') + b'\0'))
    o_cdata = put(uleb(0) + uleb(0) + uleb(0) + uleb(1) + uleb(0) + uleb(0x101) + uleb(0))   # one virtual method: public native onTouch
    items = [(0x0000, 1, 0), (0x0001, n_str, o_str), (0x0002, n_type, o_type), (0x0003, n_proto, o_proto), (0x0005, n_meth, o_meth), (0x0006, n_cls, o_cls),
             (0x1001, 2, o_params), (0x2002, n_str, o_sdata[0]), (0x2000, 1, o_cdata)]
    o_map = o_data + len(data) + (-(o_data + len(data)) % 4); items.append((0x1000, 1, o_map))
    put(struct.pack('<I', len(items)) + b''.join(struct.pack('<HHII', t, 0, n, o) for t, n, o in items), 4)
    size = o_data + len(data)
    body = bytearray()
    body += b''.join(struct.pack('<I', o) for o in o_sdata)
    body += b''.join(struct.pack('<I', S(t)) for t in TYPES)
    body += struct.pack('<III', S('ZLL'), T('Z'), o_params)
    body += struct.pack('<HHI', T('Lorg/nx2a/CompanionTouch;'), 0, S('onTouch'))
    body += struct.pack('<IIIIIIII', T('Lorg/nx2a/CompanionTouch;'), 0x11, T('Ljava/lang/Object;'), o_ifaces, NO_INDEX, 0, o_cdata, 0)
    head = struct.pack('<8sI20sIIIIIIIIIIIIIIIIIIII', b'dex\n035\0', 0, b'\0' * 20, size, 0x70, 0x12345678, 0, 0, o_map,
                       n_str, o_str, n_type, o_type, n_proto, o_proto, 0, 0, n_meth, o_meth, n_cls, o_cls, size - o_data, o_data)
    dex = bytearray(head + body + data); assert len(dex) == size and len(head) == 0x70
    dex[12:32] = hashlib.sha1(dex[32:]).digest()
    dex[8:12] = struct.pack('<I', zlib.adler32(bytes(dex[12:])))
    return bytes(dex)


if __name__ == '__main__':
    d = build()
    rows = ',\n'.join('    ' + ', '.join(f'0x{b:02x}' for b in d[i:i + 16]) for i in range(0, len(d), 16))
    sys.stdout.write(f'// Generated by tools/companion_dex.py (kalasyan fork): org.nx2a.CompanionTouch, a View.OnTouchListener whose onTouch is native\n'
                     f'#pragma once\nstatic const unsigned char COMPANION_TOUCH_DEX[{len(d)}] = {{\n{rows}\n}};\n')
